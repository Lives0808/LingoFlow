const SCRIPT = `
(function () {
  var root = document.documentElement;
  var toggle = document.getElementById('theme-toggle');
  if (toggle) {
    toggle.addEventListener('click', function () {
      var current = root.getAttribute('data-theme');
      root.setAttribute('data-theme', current === 'dark' ? 'light' : 'dark');
    });
  }
  // Real DOM overflow measurement: the dashboard validates fit, not just metrics.
  var demoNodes = document.querySelectorAll('.demo');
  demoNodes.forEach(function (node) {
    var limits = node.style.maxWidth;
    if (!limits) return;
    if (node.scrollWidth > node.clientWidth + 1) {
      node.classList.add('overflow');
      var flag = node.parentElement && node.parentElement.querySelector('.overflow-flag');
      if (flag) flag.hidden = false;
    }
  });
  // Filtering
  function applyFilters() {
    var sev = (document.getElementById('filter-severity') || {}).value || '';
    var code = (document.getElementById('filter-code') || {}).value || '';
    var locale = (document.getElementById('filter-locale') || {}).value || '';
    document.querySelectorAll('#issues-table tbody tr').forEach(function (row) {
      var show = (!sev || row.dataset.severity === sev) && (!code || row.dataset.code === code) && (!locale || row.dataset.locale === locale);
      row.style.display = show ? '' : 'none';
    });
  }
  ['filter-severity', 'filter-code', 'filter-locale'].forEach(function (id) {
    var node = document.getElementById(id);
    if (node) node.addEventListener('change', applyFilters);
  });
  var pseudoToggle = document.getElementById('pseudo-toggle');
  if (pseudoToggle) {
    pseudoToggle.addEventListener('click', function () {
      document.querySelectorAll('.target').forEach(function (cell) {
        if (cell.dataset.pseudo) cell.textContent = cell.dataset.pseudo;
      });
    });
  }
})();
`;
